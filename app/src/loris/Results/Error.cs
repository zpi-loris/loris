namespace Loris.Results;

// Adapted from "Result Pattern in .NET" by Mukesh Murugan
// Source: https://codewithmukesh.com/blog/result-pattern-dotnet/

public enum ErrorType
{
    Failure = 0,
    Validation = 1,
    NotFound = 2,
    Conflict = 3,
    Forbidden = 4,
    Upstream = 5,
}

public readonly record struct Error(string Code, string Description, ErrorType Type)
{
    public static readonly Error None = new(string.Empty, string.Empty, ErrorType.Failure);

    public static Error Validation(string code, string description) =>
        new(code, description, ErrorType.Validation);

    public static Error NotFound(string code, string description) =>
        new(code, description, ErrorType.NotFound);

    public static Error Conflict(string code, string description) =>
        new(code, description, ErrorType.Conflict);

    public static Error Forbidden(string code, string description) =>
        new(code, description, ErrorType.Forbidden);

    public static Error Upstream(string code, string description) =>
        new(code, description, ErrorType.Upstream);
}
