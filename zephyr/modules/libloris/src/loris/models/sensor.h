#ifndef LORIS_SENSOR_H
#define LORIS_SENSOR_H

#include <inttypes.h>
#include <stdbool.h>
#include <zephyr/sys/slist.h>

#include "loris/str.h"
#include "loris/models/report.h"

/*
 * Value type used in capabilities.sensor
 */
typedef enum value_type {
    /* General */
    VALUE_TYPE_UNSPECIFIED     = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_UNSPECIFIED,
    VALUE_TYPE_NUMERIC         = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_NUMERIC,
    VALUE_TYPE_TEXT            = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_TEXT,
    VALUE_TYPE_BOOL            = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_BOOL,
    /* Common */
    VALUE_TYPE_TEMPERATURE     = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_TEMPERATURE,
    VALUE_TYPE_PRESSURE        = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_PRESSURE,
    VALUE_TYPE_FREQUENCY       = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_FREQUENCY,
    VALUE_TYPE_MOISTURE        = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_MOISTURE,
    VALUE_TYPE_UPTIME          = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_UPTIME,
    VALUE_TYPE_AREA            = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_AREA,
    VALUE_TYPE_DISTANCE        = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_DISTANCE,
    VALUE_TYPE_DURATION        = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_DURATION,
    VALUE_TYPE_ILLUMINANCE     = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_ILLUMINANCE,
    VALUE_TYPE_WATER           = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_WATER,
    VALUE_TYPE_WEIGHT          = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_WEIGHT,
    /* Air index */
    VALUE_TYPE_AQI             = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_AQI,
    VALUE_TYPE_CO2             = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_CO2,
    VALUE_TYPE_PM1             = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_PM1,
    VALUE_TYPE_PM25            = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_PM25,
    VALUE_TYPE_PM4             = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_PM4,
    VALUE_TYPE_PM10            = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_PM10,
    VALUE_TYPE_HUMIDITY        = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_HUMIDITY,
    /* Wind */
    VALUE_TYPE_WIND_SPEED      = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_WIND_SPEED,
    /* Electricity */
    VALUE_TYPE_BATTERY         = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_BATTERY,
    VALUE_TYPE_ENERGY          = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_ENERGY,
    VALUE_TYPE_VOLTAGE         = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_VOLTAGE,
    VALUE_TYPE_CURRENT         = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_CURRENT,
    /* Transmission */
    VALUE_TYPE_DATA_RATE       = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_DATA_RATE,
    VALUE_TYPE_DATA_SIZE       = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_DATA_SIZE,
    VALUE_TYPE_SIGNAL_STRENGTH = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_SIGNAL_STRENGTH,
    /* Earth */
    VALUE_TYPE_PH              = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_PH,
    VALUE_TYPE_POTASSIUM       = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_POTASSIUM,
    VALUE_TYPE_PHOSPHORUS      = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_PHOSPHORUS,
    VALUE_TYPE_NITROGEN        = PROTOCOL_V1_VALUE_TYPE_VALUE_TYPE_NITROGEN,
} value_type_t;

BUILD_ASSERT((int)VALUE_TYPE_UNSPECIFIED == (int)_PROTOCOL_V1_VALUE_TYPE_MIN, "Enums don't match, possible missing members");
BUILD_ASSERT((int)VALUE_TYPE_NITROGEN    == (int)_PROTOCOL_V1_VALUE_TYPE_MAX, "Enums don't match, possible missing members");

typedef struct sensor {
  sys_snode_t node;

  int32_t id;
  str_t name;
  str_t description;
  value_type_t value_type;

  // Determines whether 'unit' field is present
  bool has_unit;
  // Unit is optional, if not present should always be set to LORIS_STR_NONE
  str_t unit;
  report_t (*read_func)(struct sensor *sensor);
  // wake_interval_sec is optional, if not present should always be set to 0
  int32_t wake_interval_sec;
} sensor_t;

#endif
